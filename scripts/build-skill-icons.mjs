// Build-time generator for the `skills` card: rasterizes every simple-icons logo
// into a GRID x GRID 1-bit bitmap and writes src/skillIconsData.js. Rendering at
// request time then needs no SVG rasterizer, only the precomputed bitmaps.
//
//   npm run build:icons
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import * as simpleIcons from "simple-icons";
import { Resvg } from "@resvg/resvg-js";

const GRID = 20;        // bitmap edge in pixels (one half-block cell each)
const SUPERSAMPLE = 8;  // raster px per bitmap pixel
const THRESHOLD = 0.45; // coverage needed to light a pixel

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_PATH = path.resolve(__dirname, "..", "src", "skillIconsData.js");

function rasterize(svgPath) {
  const px = GRID * SUPERSAMPLE;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 24 24"><path d="${svgPath}" fill="#000"/></svg>`;
  const alpha = new Resvg(svg).render().pixels;
  const bits = new Uint8Array(Math.ceil((GRID * GRID) / 8));
  for (let gy = 0; gy < GRID; gy++) {
    for (let gx = 0; gx < GRID; gx++) {
      let sum = 0;
      for (let y = 0; y < SUPERSAMPLE; y++) {
        for (let x = 0; x < SUPERSAMPLE; x++) {
          sum += alpha[((gy * SUPERSAMPLE + y) * px + gx * SUPERSAMPLE + x) * 4 + 3];
        }
      }
      if (sum / (SUPERSAMPLE * SUPERSAMPLE * 255) > THRESHOLD) {
        const i = gy * GRID + gx;
        bits[i >> 3] |= 1 << (7 - (i & 7));
      }
    }
  }
  return Buffer.from(bits).toString("base64");
}

// 5x7 pixel font for monogram tiles (brands that simple-icons no longer ships).
const GLYPHS = {
  A: [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
  C: [".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."],
  I: ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "#####"],
  L: ["#....", "#....", "#....", "#....", "#....", "#....", "#####"],
  N: ["#...#", "##..#", "##..#", "#.#.#", "#..##", "#..##", "#...#"],
  S: [".####", "#....", "#....", ".###.", "....#", "....#", "####."],
  V: ["#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."],
  W: ["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#"],
  Z: ["#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"],
  "#": [".#.#.", ".#.#.", "#####", ".#.#.", "#####", ".#.#.", ".#.#."]
};

// Filled rounded tile with the letters knocked out, like the JS / TS logos.
function monogram(text) {
  const on = Array.from({ length: GRID }, () => new Array(GRID).fill(true));
  for (const [x, y] of [[0, 0], [GRID - 1, 0], [0, GRID - 1], [GRID - 1, GRID - 1]]) on[y][x] = false;
  const width = text.length * 6 - 1;
  const left = Math.floor((GRID - width) / 2);
  const top = Math.floor((GRID - 7) / 2);
  [...text].forEach((ch, i) => {
    GLYPHS[ch].forEach((row, dy) => {
      [...row].forEach((cell, dx) => {
        if (cell === "#") on[top + dy][left + i * 6 + dx] = false;
      });
    });
  });
  const bits = new Uint8Array(Math.ceil((GRID * GRID) / 8));
  on.flat().forEach((lit, i) => { if (lit) bits[i >> 3] |= 1 << (7 - (i & 7)); });
  return Buffer.from(bits).toString("base64");
}

const MONOGRAMS = [
  { slug: "csharp", title: "C#", hex: "9B4F96", text: "C#" },
  { slug: "windows", title: "Windows", hex: "0078D4", text: "WIN" },
  { slug: "amazonwebservices", title: "AWS", hex: "FF9900", text: "AWS" },
  { slug: "microsoftazure", title: "Azure", hex: "0089D6", text: "AZ" },
  { slug: "visualstudiocode", title: "VS Code", hex: "007ACC", text: "VS" },
  { slug: "slack", title: "Slack", hex: "E01E5A", text: "SL" }
];

const icons = {};
for (const icon of Object.values(simpleIcons)) {
  if (!icon?.slug || !icon.path) continue;
  icons[icon.slug] = [icon.title, icon.hex, rasterize(icon.path)];
}
for (const m of MONOGRAMS) {
  if (!icons[m.slug]) icons[m.slug] = [m.title, m.hex, monogram(m.text)];
}

const pkg = JSON.parse(fs.readFileSync(path.resolve(__dirname, "..", "node_modules", "simple-icons", "package.json"), "utf8"));
const header = `// Generated by scripts/build-skill-icons.mjs from simple-icons@${pkg.version} (CC0-1.0). Do not edit.
// slug -> [title, brand hex, base64 ${GRID}x${GRID} 1-bit bitmap, row-major MSB first]
`;
// One icon per line keeps diffs readable when simple-icons is bumped.
const body = Object.keys(icons).sort().map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(icons[slug])}`).join(",\n");
fs.writeFileSync(OUT_PATH, `${header}export const ICON_GRID = ${GRID};\nexport const ICONS = {\n${body}\n};\n`);
console.log(`wrote ${Object.keys(icons).length} icons -> ${path.relative(process.cwd(), OUT_PATH)}`);
